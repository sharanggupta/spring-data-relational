CREATE TABLE DUMMY_ENTITY
(
    ID   BIGINT GENERATED BY DEFAULT AS IDENTITY ( START WITH 1 ) PRIMARY KEY,
    NAME VARCHAR(100)
);
CREATE TABLE CHILD_ELEMENT
(
    CHILD_ID     BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    NAME         VARCHAR(100),
    DUMMY_ENTITY BIGINT,
    FOREIGN KEY (DUMMY_ENTITY) REFERENCES DUMMY_ENTITY (ID)
);
CREATE TABLE GRAND_CHILD_ELEMENT
(
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    CONTENT       VARCHAR(100),
    CHILD_ELEMENT BIGINT,
    FOREIGN KEY (CHILD_ELEMENT) REFERENCES CHILD_ELEMENT (CHILD_ID)
);
CREATE TABLE READ_ONLY_ELEMENT
(
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    NAME         VARCHAR(100),
    DUMMY_ENTITY BIGINT
);
CREATE TABLE LIST_ROOT
(
    ID   BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    NAME VARCHAR(100)
);
CREATE TABLE LIST_CHILD
(
    NAME          VARCHAR(100),
    LIST_ROOT     BIGINT,
    LIST_ROOT_KEY BIGINT,
    PRIMARY KEY (LIST_ROOT, LIST_ROOT_KEY),
    FOREIGN KEY (LIST_ROOT) REFERENCES LIST_ROOT (ID)
);
CREATE TABLE LIST_GRAND_CHILD
(
    NAME           VARCHAR(100),
    LIST_ROOT      BIGINT,
    LIST_ROOT_KEY  BIGINT,
    LIST_CHILD_KEY BIGINT,
    PRIMARY KEY (LIST_ROOT, LIST_ROOT_KEY, LIST_CHILD_KEY),
    FOREIGN KEY (LIST_ROOT, LIST_ROOT_KEY) REFERENCES LIST_CHILD (LIST_ROOT, LIST_ROOT_KEY)
);
